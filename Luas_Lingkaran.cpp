#include <iostream>
using namespace std;

int main() {
    // Langkah 1: Definisikan jari-jari dan phi
    float phi = 3.14, r = 7, luas;

    // Langkah 2: Hitung luas
    luas = phi * r * r;

    // Langkah 3: Cetak hasil
    cout << "Luas lingkaran dengan jari-jari 7 cm adalah: " << luas << " cm²" << endl;

    return 0;
}
